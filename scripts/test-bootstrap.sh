#!/usr/bin/env sh
set -eu
PROJECT_ROOT=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
TEST_ROOT=$(mktemp -d)
trap 'rm -rf "$TEST_ROOT"' EXIT HUP INT TERM
mkdir -p "$TEST_ROOT/project/scripts" "$TEST_ROOT/project/backend" "$TEST_ROOT/bin"
cp "$PROJECT_ROOT/scripts/bootstrap.sh" "$TEST_ROOT/project/scripts/bootstrap.sh"
cat > "$TEST_ROOT/bin/docker" <<'MOCK'
#!/usr/bin/env sh
printf '%s\n' "$*" >> "$DOCKER_LOG"
exit "${DOCKER_EXIT:-0}"
MOCK
chmod +x "$TEST_ROOT/bin/docker"
export PATH="$TEST_ROOT/bin:$PATH"
export DOCKER_LOG="$TEST_ROOT/docker.log"
cd "$TEST_ROOT"
if sh project/scripts/bootstrap.sh > output 2>&1; then
  echo "FAIL: missing environment must fail" >&2
  exit 1
fi
test ! -f "$DOCKER_LOG"
printf 'APP_KEY=\n' > project/.env
export DOCKER_EXIT=1
if sh project/scripts/bootstrap.sh > output 2>&1; then
  echo "FAIL: invalid Compose configuration must fail" >&2
  exit 1
fi
test "$(wc -l < "$DOCKER_LOG" | tr -d ' ')" = 1
unset DOCKER_EXIT
rm "$DOCKER_LOG"
sh project/scripts/bootstrap.sh > output 2>&1
grep -q '^compose -f compose.yaml pull app$' "$DOCKER_LOG"
grep -q 'app php artisan key:generate --force' "$DOCKER_LOG"
# Existing encryption keys must never be regenerated by setup.
test -L project/backend/.env
test project/.env -ef project/backend/.env
grep -q -- '/project/.env:/var/www/html/.env' "$DOCKER_LOG"
rm "$DOCKER_LOG"
sh project/scripts/bootstrap.sh --pull > output 2>&1
grep -q '^compose -f compose.yaml pull app$' "$DOCKER_LOG"
if grep -q ' build app$' "$DOCKER_LOG"; then
  echo 'FAIL: published-image setup rebuilt the application' >&2
  exit 1
fi
rm "$DOCKER_LOG"
sh project/scripts/bootstrap.sh --dev > output 2>&1
grep -q '^compose -f compose.yaml -f compose.dev.yaml build app$' "$DOCKER_LOG"
grep -q '^compose -f compose.yaml -f compose.dev.yaml run .*php artisan key:generate --force$' "$DOCKER_LOG"
printf 'APP_KEY=existing-private-key\n' > project/.env
rm "$DOCKER_LOG"
sh project/scripts/bootstrap.sh > output 2>&1
if grep -q 'key:generate' "$DOCKER_LOG"; then
  echo 'FAIL: existing application key was regenerated' >&2
  exit 1
fi
# A separate file must not silently replace the shared configuration.
unlink project/backend/.env
printf 'APP_KEY=separate-key\n' > project/backend/.env
if sh project/scripts/bootstrap.sh > output 2>&1; then
  echo 'FAIL: separate backend environment was accepted' >&2
  exit 1
fi
grep -q '^APP_KEY=separate-key$' project/backend/.env
echo "Bootstrap contract checks passed."
