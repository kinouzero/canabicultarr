test('user workspace filters accounts, previews inherited permissions and duplicates a profile without changing it', async ({ page }) => {
 const { errors } = await insightRoutes(page);
 const profiles = [{ id: 'grower', name: 'Grower', description: null, permissions: ['plants.manage'], isArchived: false, version: 1, assignedUsers: 1 }];
 const member = { id: 'member-one', name: 'Fictional grower', email: 'grower@example.test', isActive: true, permissionGrants: ['inventory.manage'], permissionDenials: [], permissions: ['plants.manage', 'inventory.manage'], permissionRoles: [{ id: 'grower', name: 'Grower', permissions: ['plants.manage'] }], locationAccess: [], oidcLinked: false };
 const meta = { current_page: 1, last_page: 1, per_page: 20, total: 1 };
 const userQueries: URL[] = []; const writes: { path: string; input: Record<string, unknown> }[] = [];
 await page.route('**/api/v1/auth/user', route => route.fulfill({ json: { data: { id: 'fictional-admin', name: 'Fictional admin', email: 'admin@example.test', isActive: true, permissions: ['administration.view'], locationAccess: null } } }));
 await page.route('**/api/v1/permission-roles**', route => {
  if (route.request().method() === 'GET') return route.fulfill({ json: { data: profiles, meta } });
  writes.push({ path: 'profile', input: route.request().postDataJSON() });
  return route.fulfill({ status: 201, json: { data: { ...profiles[0], id: 'copy', ...route.request().postDataJSON() } } });
 });
 await page.route('**/api/v1/users**', route => {
  if (route.request().method() !== 'GET') throw new Error('This flow must not modify accounts');
  userQueries.push(new URL(route.request().url()));
  return route.fulfill({ json: { data: [member], meta, summary: { total: 3, active: 2, inactive: 1, administrators: 1 } } });
 });
 await page.reload(); await openModule(page, 'users');
 await expect(page.getByTestId('workspace-section-users')).toHaveAttribute('role', 'tab');
 await (await revealTabbedControl(page.locator('#users-status-filter'))).selectOption('inactive');
 await expect.poll(() => userQueries.at(-1)?.searchParams.get('status')).toBe('inactive');
 await page.getByRole('button', { name: 'Modifier Fictional grower', exact: true }).click();
 const editor = page.getByRole('dialog');
 await expect(editor.getByRole('tab')).toHaveCount(4);
 await editor.getByRole('tab', { name: 'Profils et droits', exact: true }).click();
 await expect(editor.locator('.user-profile-chips')).toContainText('Cultivateur');
 await expect(editor.locator('#user-role')).toHaveCount(0);
 const inherited = editor.getByLabel(/Gérer les plantes et les actions de culture/).and(page.locator('select'));
 await expect(inherited).toHaveValue('inherit'); await expect(inherited).toBeEnabled();
 await expect(editor.getByLabel(/Gérer le stock et ses mouvements/).and(page.locator('select'))).toHaveValue('allow');
 await editor.getByRole('tab', { name: 'Compte', exact: true }).click();
 await (await revealTabbedControl(editor.locator('#user-name'))).fill('');
 await editor.getByRole('tab', { name: 'Mot de passe', exact: true }).click();
 await editor.getByRole('button', { name: 'Enregistrer le compte', exact: true }).click();
 await expect(editor.getByRole('tab', { name: 'Compte', exact: true })).toHaveAttribute('aria-selected', 'true');
 await expect(editor.locator('#user-name')).toBeFocused();
 await (await revealTabbedControl(editor.locator('#user-name'))).fill('Fictional grower');
 await editor.getByRole('button', { name: 'Annuler', exact: true }).click();
 await page.getByTestId('workspace-section-profiles').click();
 await expect(page.getByRole('heading', { name: 'Cultivateur', exact: true })).toBeVisible();
 await page.getByRole('button', { name: 'Créer à partir de Cultivateur', exact: true }).click();
 await expect(page.locator('#profile-name')).toHaveValue('Copie de Cultivateur');
 await page.getByRole('dialog').getByRole('tab', { name: 'Droits', exact: true }).click(); await expect(page.getByRole('switch', { name: 'Gérer les plantes et les actions de culture', exact: true })).toBeChecked();
 await (await revealTabbedControl(page.locator('#profile-name'))).fill('Fictional profile copy');
 await page.getByRole('button', { name: /^(?:Enregistrer le profil|Créer)$/, exact: true }).click();
 await expect.poll(() => writes).toEqual([{ path: 'profile', input: { name: 'Fictional profile copy', description: null, permissions: ['plants.manage'], is_archived: false } }]);
 await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
 expect(errors).toEqual([]);
});

test('multiple profiles and individual allow or deny exceptions save without an independent user role', async ({ page }) => {
 const { errors } = await insightRoutes(page);
 const profiles = [{ id: 'grower', name: 'Grower', permissions: ['plants.manage'], isArchived: false, version: 1, assignedUsers: 1 }, { id: 'observer', name: 'Observer', permissions: [], isArchived: false, version: 1, assignedUsers: 0 }, { id: 'technician', name: 'Technician', permissions: ['assets.manage'], isArchived: false, version: 1, assignedUsers: 0 }];
 let member = { id: 'member-one', name: 'Fictional grower', email: 'grower@example.test', isActive: true, permissionGrants: [] as string[], permissionDenials: [] as string[], permissions: ['plants.manage'], permissionRoles: [profiles[0]], locationAccess: null };
 const writes: Record<string, unknown>[] = []; const meta = { current_page: 1, last_page: 1, total: 1, per_page: 20 };
 await page.route('**/api/v1/auth/user', route => route.fulfill({ json: { data: { id: 'admin', name: 'Admin', email: 'admin@example.test', isActive: true, permissions: ['administration.view'], permissionRoles: [{ id: 'administrator', name: 'Administrator' }]} } }));
 await page.route('**/api/v1/permission-roles**', route => route.fulfill({ json: { data: profiles, meta: { ...meta, total: 2 } } }));
 await page.route('**/api/v1/users**', async route => {
  if (route.request().method() === 'GET') return route.fulfill({ json: { data: [member], meta } });
  const input = route.request().postDataJSON(); writes.push(input);
  member = { ...member, permissionRoles: profiles.filter(profile => input.permission_role_ids.includes(profile.id)), permissionGrants: input.permission_grants, permissionDenials: input.permission_denials, permissions: ['inventory.manage'] };
  return route.fulfill({ json: { data: member } });
 });
 await page.reload(); await openModule(page, 'users');
 await expect(page.locator('#users-role-filter')).toHaveCount(0);
 await page.getByRole('button', { name: 'Modifier Fictional grower', exact: true }).click();
 const editor = page.getByRole('dialog');
 await expect(editor.getByRole('tab')).toHaveCount(4);
 await editor.getByRole('tab', { name: 'Profils et droits', exact: true }).click();
 await (await revealTabbedControl(editor.getByLabel(/Gérer les plantes et les actions de culture/).and(editor.locator('select')))).selectOption('deny');
 await (await revealTabbedControl(editor.getByLabel(/Gérer le stock et ses mouvements/).and(editor.locator('select')))).selectOption('allow');
 await editor.getByRole('button', { name: /^(?:Enregistrer le compte|Créer)$/, exact: true }).click();
 await expect(editor).toHaveCount(0);
 expect(writes).toHaveLength(1);
 expect(writes[0]).toMatchObject({ permission_role_ids: ['grower'], permission_grants: ['inventory.manage'], permission_denials: ['plants.manage'] });
 expect(writes[0]).not.toHaveProperty('role');
 await page.getByRole('button', { name: 'Modifier Fictional grower', exact: true }).click();
 await editor.getByRole('tab', { name: 'Profils et droits', exact: true }).click();
 await expect(editor.getByLabel(/Gérer les plantes et les actions de culture/).and(page.locator('select'))).toHaveValue('deny');
 await expect(editor.getByLabel(/Gérer le stock et ses mouvements/).and(page.locator('select'))).toHaveValue('allow');
 await (await revealTabbedControl(editor.locator('#user-permission-profile'))).selectOption('observer');
 await (await revealTabbedControl(editor.locator('#user-permission-profile'))).selectOption('technician');
 await expect(editor.locator('.user-profile-chips')).toContainText('Technicien');
 await editor.getByLabel('Retirer Cultivateur', { exact: true }).click();
 await expect(editor.getByLabel(/Gérer les plantes et les actions de culture/).and(page.locator('select'))).toHaveValue('deny');
 await editor.getByRole('button', { name: /^(?:Enregistrer le compte|Créer)$/, exact: true }).click();
 await expect(editor).toHaveCount(0); expect(writes[1]).toMatchObject({ permission_role_ids: ['observer', 'technician'], permission_denials: ['plants.manage'] });
 expect(errors).toEqual([]);
});
