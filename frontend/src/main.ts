import { createApp, h } from 'vue';
import AppTheme from './components/AppTheme.vue';
import { initializeTheme } from './lib/theme';
import { createI18n } from 'vue-i18n';
import './styles/spacing.css';
import './styles/dialogs.css';
import './styles/pages.css';
import './styles/operational.css';
import './styles/insights.css';
import './styles/messages.css';
import './styles/list-actions.css';
import './styles/appearance.css';
import './styles/selects.css';
import './styles/search-filters.css';
import './styles/header-actions.css';
import './styles/form-controls.css';
import './styles/naive.css';
import './styles/disclosures.css';
import { responsiveSelect } from './lib/responsive-select';
import { initializeAppearance } from './lib/appearance';
import App from './App.vue';
import { router } from './router';
import { resolveLocale } from './lib/locale';
import { registerOfflineFallback } from './pwa';
import en from './locales/en/common.json';
import fr from './locales/fr/common.json';
initializeAppearance(); initializeTheme();
const savedLocale = localStorage.getItem('locale');
const selected = resolveLocale(savedLocale, navigator.languages?.length ? navigator.languages : [navigator.language]);
const i18n = createI18n({ legacy: false, locale: selected, fallbackLocale: 'en', messages: { en, fr } });
const app = createApp({ render: () => h(AppTheme, null, { default: () => h(App) }) }).use(i18n).directive('app-select', responsiveSelect).use(router);
void router.isReady().then(() => app.mount('#app'));

registerOfflineFallback();
